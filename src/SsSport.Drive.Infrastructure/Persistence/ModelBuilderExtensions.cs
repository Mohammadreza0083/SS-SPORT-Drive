using Microsoft.EntityFrameworkCore;
using SsSport.Drive.Domain.Primitives;

namespace SsSport.Drive.Infrastructure.Persistence;

/// <summary>EF Core model conventions shared by every SS-SPORT Drive context.</summary>
public static class ModelBuilderExtensions
{
    /// <summary>The shadow property Npgsql maps to the <c>xmin</c> system column.</summary>
    public const string RowVersionProperty = "RowVersion";

    /// <summary>
    /// Keeps <see cref="AggregateRoot{TId}.DomainEvents"/> out of the database model. Call it after every entity is configured.
    /// </summary>
    /// <param name="modelBuilder">The model builder.</param>
    /// <returns>The same model builder, for chaining.</returns>
    public static ModelBuilder IgnoreDomainEvents(this ModelBuilder modelBuilder)
    {
        ArgumentNullException.ThrowIfNull(modelBuilder);

        foreach (var entityType in modelBuilder.Model.GetEntityTypes().Where(type => IsAggregateRoot(type.ClrType)).ToList())
        {
            modelBuilder.Entity(entityType.ClrType).Ignore(nameof(AggregateRoot<int>.DomainEvents));
        }

        return modelBuilder;
    }

    /// <summary>
    /// Marks every <see cref="Guid"/> key as set by the domain (time-ordered v7 ids), never generated by the database,
    /// so new child entities added to a tracked aggregate are inserted rather than treated as existing rows.
    /// </summary>
    /// <param name="modelBuilder">The model builder.</param>
    /// <returns>The same model builder, for chaining.</returns>
    public static ModelBuilder UseClientGeneratedGuidKeys(this ModelBuilder modelBuilder)
    {
        ArgumentNullException.ThrowIfNull(modelBuilder);
        foreach (var key in modelBuilder.Model.GetEntityTypes().Where(type => !type.IsOwned()).Select(type => type.FindPrimaryKey()))
        {
            if (key is { Properties: [{ ClrType: var clrType } property] } && clrType == typeof(Guid))
            {
                property.ValueGenerated = Microsoft.EntityFrameworkCore.Metadata.ValueGenerated.Never;
            }
        }

        return modelBuilder;
    }

    /// <summary>
    /// Gives every aggregate root optimistic concurrency on PostgreSQL's <c>xmin</c> system column: when two editors
    /// change the same row, the second save fails instead of silently overwriting the first.
    /// </summary>
    /// <param name="modelBuilder">The model builder.</param>
    /// <returns>The same model builder, for chaining.</returns>
    public static ModelBuilder UseRowVersionConcurrency(this ModelBuilder modelBuilder)
    {
        ArgumentNullException.ThrowIfNull(modelBuilder);
        foreach (var entityType in modelBuilder.Model.GetEntityTypes().Where(type => IsAggregateRoot(type.ClrType)).ToList())
        {
            modelBuilder.Entity(entityType.ClrType).Property<uint>(RowVersionProperty).IsRowVersion();
        }

        return modelBuilder;
    }

    /// <summary>Checks whether a type derives from <see cref="AggregateRoot{TId}"/> for any identifier type.</summary>
    /// <param name="type">The CLR type to check.</param>
    /// <returns><see langword="true"/> for aggregate roots.</returns>
    private static bool IsAggregateRoot(Type type)
    {
        for (var current = type.BaseType; current is not null; current = current.BaseType)
        {
            if (current.IsGenericType && current.GetGenericTypeDefinition() == typeof(AggregateRoot<>))
            {
                return true;
            }
        }

        return false;
    }
}
